/// Icône d'une clé normalisée du catalogue (repli : icône par défaut).
IconData categoryIconFor(String? iconKey) =>
    categoryIconByKey[iconKey] ?? defaultCategoryIcon;

/// Pictogramme d'un métier ou d'une prestation.
Widget homeCategoryIcon(Category c, {required Color color, double size = 22}) {
  return FaIcon(categoryIconFor(c.iconKey), color: color, size: size);
}
